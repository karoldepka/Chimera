//! Rust backend: emits a single `main.rs` that uses the `rt` runtime module.

use std::collections::HashSet;

use crate::ast::*;
use crate::common::{contract_msg, free_names, is_formula, order_args, Decls};
use crate::desugar::is_sheets_lazy;
use crate::sema::{is_builtin, Info};

const RUST_KW: &[&str] = &[
    "as", "async", "await", "box", "const", "crate", "dyn", "enum", "extern", "fn", "impl", "let", "loop", "mod", "move",
    "mut", "pub", "ref", "self", "Self", "static", "struct", "super", "trait", "type", "unsafe", "use", "where", "yield",
    "macro", "priv", "typeof", "unsized", "virtual", "final", "do", "try", "abstract", "become", "gen",
];

pub fn rid(n: &str) -> String {
    if matches!(n, "self" | "Self" | "super" | "crate") { return format!("{}_", n); }
    if RUST_KW.contains(&n) { format!("r#{}", n) } else { n.to_string() }
}
fn fname(n: &str) -> String { if n == "main" { "chimera_main".into() } else { format!("f_{}", n) } }
fn lit(s: &str) -> String { format!("{:?}", s) }

pub fn generate(p: &Program, info: &Info) -> String {
    let d = Decls::new(p);
    let mut g = Gen { info, d: &d, scopes: vec![], class: None, loops: vec![], n: 0, in_generic: false };
    let mut out = String::new();
    out.push_str("// Generated by the Chimera compiler. Do not edit.\n#![allow(warnings, unused)]\nmod rt;\nuse rt::Value;\n\n");

    // enums
    for e in &d.enums {
        for v in &e.variants {
            let ps: Vec<String> = v.fields.iter().map(|f| format!("{}: Value", rid(&f.name))).collect();
            let names: Vec<String> = v.fields.iter().map(|f| lit(&f.name)).collect();
            let vals: Vec<String> = v.fields.iter().map(|f| rid(&f.name)).collect();
            out.push_str(&format!("fn {}__{}({}) -> Value {{ rt::variant({}, {}, &[{}], vec![{}]) }}\n",
                e.name, v.name, ps.join(", "), lit(&e.name), lit(&v.name), names.join(", "), vals.join(", ")));
        }
    }
    // functions (native-lowered where possible)
    let sigs = crate::native::analyze(p);
    let mut ng = crate::native::NGen::new(&sigs, p);
    for decl in &p.decls {
        if let Decl::Fun(f) = decl {
            if sigs.contains_key(&f.name) { out.push_str(&ng.function(f, &fname(&f.name))); }
            else { out.push_str(&g.function(f, &fname(&f.name), None, f.name.clone())); }
        }
    }
    // classes
    let mut reg = String::new();
    for cname in &info.class_order {
        let c = d.classes[cname];
        out.push_str(&g.class(c, &mut reg));
    }
    // generic methods
    for (i, m) in d.methods.iter().enumerate() {
        g.in_generic = true;
        g.scopes = vec![HashSet::new()];
        let mut body = String::new();
        for (k, p) in m.params.iter().enumerate() {
            body.push_str(&format!("    let mut {} = __args.get({}).cloned().unwrap_or(Value::Nil);\n", rid(&p.name), k));
            g.declare(&p.name);
        }
        let b = g.expr(&m.body);
        out.push_str(&format!("fn {}__m{}(__args: Vec<Value>, __next: &dyn Fn(Vec<Value>) -> Value) -> Value {{\n{}    {}\n}}\n", m.name, i, body, b));
        let specs: Vec<String> = m.params.iter().map(|p| match &p.ty { Some(TypeNode::Name { name, .. }) => lit(name), _ => lit("Any") }).collect();
        let q = match m.qualifier.as_str() { "before" => 1, "after" => 2, "around" => 3, _ => 0 };
        reg.push_str(&format!("    rt::register_method({}, rt::GMethod {{ qual: {}, specs: &[{}], f: {}__m{} }});\n", lit(&m.name), q, specs.join(", "), m.name, i));
        g.in_generic = false;
    }
    out.push_str(&format!("\nfn register() {{\n{}}}\n\nfn main() {{\n    rt::run(|| {{ register(); chimera_main() }});\n}}\n", reg));
    out
}

struct Gen<'a> {
    info: &'a Info,
    d: &'a Decls<'a>,
    scopes: Vec<HashSet<String>>,
    class: Option<String>,
    loops: Vec<String>,
    n: usize,
    in_generic: bool,
}

impl<'a> Gen<'a> {
    fn fresh(&mut self, p: &str) -> String { self.n += 1; format!("{}{}", p, self.n) }
    fn declare(&mut self, n: &str) { self.scopes.last_mut().unwrap().insert(n.to_string()); }
    fn is_local(&self, n: &str) -> bool { self.scopes.iter().any(|s| s.contains(n)) }
    fn field(&self, n: &str) -> bool {
        self.class.as_ref().and_then(|c| self.info.classes.get(c)).map_or(false, |ci| ci.fields.iter().any(|f| f.name == n))
    }
    fn method(&self, n: &str) -> bool {
        self.class.as_ref().and_then(|c| self.info.classes.get(c)).map_or(false, |ci| ci.methods.contains_key(n))
    }

    /// `&expr` without needless clones/parens
    fn rf(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Ident(n) if self.is_local(n) => format!("&{}", rid(n)),
            ExprKind::This => "&this".into(),
            _ => { let s = self.expr(e); if s.starts_with('\'') || s.starts_with("if ") || s.starts_with("match ") { format!("&({})", s) } else { format!("&{}", s) } }
        }
    }

    // ------------------------------------------------------------ declarations
    fn params_list(&self, ps: &[Param]) -> String { ps.iter().map(|p| format!("mut {}: Value", rid(&p.name))).collect::<Vec<_>>().join(", ") }

    fn function(&mut self, f: &FunDecl, name: &str, this: Option<&str>, where_: String) -> String {
        self.scopes = vec![HashSet::new()];
        self.loops.clear();
        for p in &f.params { self.declare(&p.name); }
        let mut sig = vec![];
        if this.is_some() { sig.push("this: Value".to_string()); }
        sig.push(self.params_list(&f.params));
        let sig: Vec<String> = sig.into_iter().filter(|s| !s.is_empty()).collect();
        let mut b = String::new();
        for r in &f.requires {
            b.push_str(&format!("    if !rt::truthy({}) {{\n        rt::fail({});\n    }}\n", self.rf(&r.expr), lit(&contract_msg("precondition", &where_, r))));
        }
        let body = match &f.body { Some(e) => self.expr(e), None => "Value::Nil".into() };
        if f.ensures.is_empty() {
            b.push_str(&format!("    {}\n", body));
        } else {
            for (i, o) in f.olds.iter().enumerate() { b.push_str(&format!("    let __old{} = {};\n", i, self.expr(o))); }
            b.push_str(&format!("    let result: Value = (|| -> Value {{ {} }})();\n", body));
            self.declare("result");
            for e in &f.ensures {
                b.push_str(&format!("    if !rt::truthy({}) {{\n        rt::fail({});\n    }}\n", self.rf(&e.expr), lit(&contract_msg("postcondition", &where_, e))));
            }
            b.push_str("    result\n");
        }
        format!("fn {}({}) -> Value {{\n{}}}\n\n", name, sig.join(", "), b)
    }

    fn class(&mut self, c: &ClassDecl, reg: &mut String) -> String {
        let ci = &self.info.classes[&c.name];
        self.class = Some(c.name.clone());
        let mut out = format!("// ---- {} {} (MRO: {})\n", if c.is_trait { "trait" } else { "class" }, c.name, ci.mro.join(" -> "));
        // methods
        let mut table = vec![];
        for m in &c.methods {
            if m.body.is_none() { continue; }
            let fnn = format!("{}__{}", c.name, m.name);
            out.push_str(&self.function(m, &fnn, Some("this"), format!("{}.{}", c.name, m.name)));
            let args: Vec<String> = m.params.iter().enumerate().map(|(i, p)| {
                let def = p.default.as_ref().map(|d| { self.scopes = vec![HashSet::new()]; self.expr(d) }).unwrap_or("Value::Nil".into());
                format!("a.get({}).cloned().unwrap_or_else(|| {})", i, def)
            }).collect();
            table.push(format!("({}, |t: Value, a: Vec<Value>| {}(t{}{}))", lit(&m.name), fnn, if args.is_empty() { "" } else { ", " }, args.join(", ")));
        }
        // invariant
        let inv = if c.invariants.is_empty() { "None".to_string() } else {
            self.scopes = vec![HashSet::new()];
            let mut b = String::new();
            for i in &c.invariants {
                b.push_str(&format!("    if !rt::truthy({}) {{\n        return Some({});\n    }}\n", self.rf(&i.expr), lit(&i.tag.as_ref().map(|t| format!("{}: {}", t, i.text)).unwrap_or(i.text.clone()))));
            }
            out.push_str(&format!("fn {}__inv(this: &Value) -> Option<&'static str> {{\n    let this = this.clone();\n{}    None\n}}\n\n", c.name, b));
            format!("Some({}__inv)", c.name)
        };
        // constructor
        if !c.is_trait {
            self.scopes = vec![HashSet::new()];
            for p in &c.params { self.declare(&p.name); }
            let mut b = format!("    if !rt::begin_init(this, {}) {{ return; }}\n    let this = this.clone();\n", lit(&c.name));
            for s in &c.supers {
                let Some(pc) = self.d.classes.get(&s.name) else { continue };
                if pc.is_trait { continue; }
                let args = s.args.clone().unwrap_or_default();
                let ordered = order_args(&pc.params, &args);
                let vals: Vec<String> = pc.params.iter().enumerate().map(|(i, p)| match ordered.get(i).copied().flatten() {
                    Some(e) => self.expr(e),
                    None => p.default.as_ref().map(|d| self.expr(d)).unwrap_or("Value::Nil".into()),
                }).collect();
                b.push_str(&format!("    {}__init(&this{}{});\n", s.name, if vals.is_empty() { "" } else { ", " }, vals.join(", ")));
            }
            for p in &c.params { if p.field.is_some() { b.push_str(&format!("    rt::set(&this, {}, {}.clone());\n", lit(&p.name), rid(&p.name))); } }
            for f in &c.fields { b.push_str(&format!("    rt::set(&this, {}, {});\n", lit(&f.name), self.expr(&f.init))); }
            let ps = self.params_list(&c.params);
            out.push_str(&format!("fn {}__init(this: &Value{}{}) {{\n{}}}\n", c.name, if ps.is_empty() { "" } else { ", " }, ps, b));
            let names: Vec<String> = c.params.iter().map(|p| rid(&p.name)).collect();
            let plain: Vec<String> = c.params.iter().map(|p| format!("{}: Value", rid(&p.name))).collect();
            out.push_str(&format!("fn {}__new({}) -> Value {{\n    let this = rt::new_obj({});\n    {}__init(&this{}{});\n    rt::finish_new(this)\n}}\n\n",
                c.name, plain.join(", "), lit(&c.name), c.name, if names.is_empty() { "" } else { ", " }, names.join(", ")));
        }
        let mro: Vec<String> = ci.mro.iter().map(|m| lit(m)).collect();
        let fields: Vec<String> = ci.fields.iter().map(|f| lit(&f.name)).collect();
        reg.push_str(&format!("    rt::register_class(rt::ClassInfo {{ name: {}, mro: &[{}], methods: vec![{}], invariant: {}, has_invariants: {}, data: {}, fields: &[{}] }});\n",
            lit(&c.name), mro.join(", "), table.join(", "), inv, ci.has_invariants, ci.is_data, fields.join(", ")));
        self.class = None;
        out
    }

    // ------------------------------------------------------------ statements
    fn block(&mut self, b: &Block) -> String {
        self.scopes.push(HashSet::new());
        let mut parts = vec![];
        let mut has_value = false;
        for (i, s) in b.stmts.iter().enumerate() {
            let last = i + 1 == b.stmts.len();
            match s {
                Stmt::Expr(e) if last => { parts.push(self.expr(e)); has_value = true; }
                _ => parts.push(self.stmt(s)),
            }
        }
        if !has_value { parts.push("Value::Nil".into()); }
        self.scopes.pop();
        format!("{{ {} }}", parts.join(" "))
    }

    fn stmt(&mut self, s: &Stmt) -> String {
        match s {
            Stmt::Let { name, init, .. } => {
                let v = self.expr(init);
                self.declare(name);
                format!("let mut {}: Value = {};", rid(name), v)
            }
            Stmt::Assign { target, value, .. } => {
                let v = self.expr(value);
                // in-place fast paths for `xs = xs.push(v)` / `m = m.assoc(k, v)` (copy-on-write via Rc::make_mut)
                if let (ExprKind::Ident(n), ExprKind::Call(c, args)) = (&target.kind, &value.kind) {
                    if let ExprKind::Member { obj, name, safe: false } = &c.kind {
                        if matches!(&obj.kind, ExprKind::Ident(o) if o == n) && self.is_local(n) && args.iter().all(|a| a.name.is_none()) {
                            if (name == "push" || name == "conj") && args.len() == 1 { let x = self.expr(&args[0].value); return format!("rt::push_mut(&mut {}, {});", rid(n), x); }
                            if name == "assoc" && args.len() == 2 { let k = self.expr(&args[0].value); let x = self.expr(&args[1].value); return format!("rt::assoc_mut(&mut {}, {}, {});", rid(n), k, x); }
                        }
                    }
                }
                if let (ExprKind::Ident(n), ExprKind::Call(c, args)) = (&target.kind, &value.kind) {
                    if let ExprKind::Member { obj, name, safe: false } = &c.kind {
                        if matches!(&obj.kind, ExprKind::Ident(o) if o == n) && !self.is_local(n) && self.field(n) && (name == "push" || name == "conj") && args.len() == 1 {
                            let x = self.expr(&args[0].value); return format!("rt::field_push_mut(&this, {}, {});", lit(n), x);
                        }
                    }
                }
                if let (ExprKind::Ident(n), ExprKind::Binary(op, l, r)) = (&target.kind, &value.kind) {
                    if (op == "&" || (op == "+" && matches!(r.kind, ExprKind::Str(_)))) && matches!(&l.kind, ExprKind::Ident(o) if o == n) && self.is_local(n) {
                        let x = self.rf(r); return format!("rt::str_append(&mut {}, {});", rid(n), x);
                    }
                }
                match &target.kind {
                    ExprKind::Ident(n) if self.is_local(n) => format!("{} = {};", rid(n), v),
                    ExprKind::Ident(n) => format!("rt::set(&this, {}, {});", lit(n), v),
                    ExprKind::Member { obj, name, .. } => match &obj.kind {
                        ExprKind::Ident(b) if self.is_local(b) => format!("{{ let __v = {}; {} = rt::set_in(&{}, {}, __v); }}", v, rid(b), rid(b), lit(name)),
                        _ => format!("rt::set(&{}, {}, {});", self.expr(obj), lit(name), v),
                    },
                    ExprKind::Index(obj, idx) => {
                        let i = self.expr(idx);
                        match &obj.kind {
                            ExprKind::Ident(b) if self.is_local(b) => format!("{{ let __v = {}; let __i = {}; {} = rt::assoc(&{}, __i, __v); }}", v, i, rid(b), rid(b)),
                            ExprKind::Ident(b) if self.field(b) => format!("{{ let __v = {}; let __i = {}; rt::set(&this, {}, rt::assoc(&rt::get(&this, {}), __i, __v)); }}", v, i, lit(b), lit(b)),
                            _ => { let o = self.expr(obj); format!("rt::index(&{}, &{});", o, i) }
                        }
                    }
                    _ => unreachable!(),
                }
            }
            Stmt::Expr(e) => format!("{};", self.expr(e)),
            Stmt::Return(v, _) => format!("return {};", v.as_ref().map(|e| self.expr(e)).unwrap_or("Value::Nil".into())),
            Stmt::Break(_) => format!("break {};", self.loops.last().cloned().unwrap_or_default()),
            Stmt::Continue(_) => format!("continue {};", self.loops.last().cloned().unwrap_or_default()),
            Stmt::While(c, b) => {
                let l = self.fresh("'l");
                let cond = self.rf(c);
                self.loops.push(l.clone());
                let body = self.block(b);
                self.loops.pop();
                format!("{}: while rt::truthy({}) {{ {}; }}", l, cond, body)
            }
            Stmt::For(name, it, b) => {
                let l = self.fresh("'l");
                if let ExprKind::Range(from, to) = &it.kind {
                    let (f, t) = (self.expr(from), self.expr(to));
                    let (iv, ev) = (self.fresh("__i"), self.fresh("__e"));
                    self.scopes.push(HashSet::from([name.clone()]));
                    self.loops.push(l.clone());
                    let body = self.block(b);
                    self.loops.pop();
                    self.scopes.pop();
                    return format!("{{ let mut {iv} = rt::as_int(&({f})); let {ev} = rt::as_int(&({t})); {l}: while {iv} < {ev} {{ let mut {n}: Value = Value::Int({iv}); {iv} += 1; {body}; }} }}", n = rid(name));
                }
                let src = self.rf(it);
                let xv = self.fresh("__x");
                self.scopes.push(HashSet::from([name.clone()]));
                self.loops.push(l.clone());
                let body = self.block(b);
                self.loops.pop();
                self.scopes.pop();
                format!("{l}: for {xv} in rt::iter({src}) {{ let mut {n}: Value = {xv}; {body}; }}", n = rid(name))
            }
        }
    }

    // ------------------------------------------------------------ expressions
    fn args_vec(&mut self, args: &[Arg]) -> String {
        let v: Vec<String> = args.iter().map(|a| self.expr(&a.value)).collect();
        format!("vec![{}]", v.join(", "))
    }
    fn ordered(&mut self, params: &[Param], args: &[Arg]) -> Vec<String> {
        let ord = order_args(params, args);
        params.iter().enumerate().map(|(i, p)| match ord.get(i).copied().flatten() {
            Some(e) => self.expr(e),
            None => p.default.as_ref().map(|d| self.expr(d)).unwrap_or("Value::Nil".into()),
        }).collect()
    }

    fn capture(&mut self, body: &[&Expr], params: &[String]) -> String {
        let mut names = HashSet::new();
        let mut uses_this = false;
        for b in body { free_names(b, &mut names, &mut uses_this); }
        let mut caps: Vec<String> = names.into_iter().filter(|n| self.is_local(n) && !params.contains(n)).collect();
        caps.sort();
        let mut s: String = caps.iter().map(|n| format!("let {} = {}.clone(); ", rid(n), rid(n))).collect();
        if uses_this && self.class.is_some() { s.push_str("let this = this.clone(); "); }
        s
    }

    fn lambda(&mut self, params: &[Param], body: &Expr) -> String {
        let pnames: Vec<String> = params.iter().map(|p| p.name.clone()).collect();
        let caps = self.capture(&[body], &pnames);
        let saved = std::mem::take(&mut self.loops);
        self.scopes.push(pnames.iter().cloned().collect());
        let binds: String = params.iter().enumerate().map(|(i, p)| format!("let mut {}: Value = __a.get({}).cloned().unwrap_or(Value::Nil); ", rid(&p.name), i)).collect();
        let b = self.expr(body);
        self.scopes.pop();
        self.loops = saved;
        format!("{{ {}rt::func(move |__a: Vec<Value>| -> Value {{ {}{} }}) }}", caps, binds, b)
    }

    fn fn_value(&self, n: &str) -> Option<String> {
        if let Some(f) = self.d.funs.get(n) {
            let args: Vec<String> = (0..f.params.len()).map(|i| format!("a.get({}).cloned().unwrap_or(Value::Nil)", i)).collect();
            return Some(format!("rt::func(|a: Vec<Value>| {}({}))", fname(n), args.join(", ")));
        }
        if let Some(c) = self.d.classes.get(n) {
            let args: Vec<String> = (0..c.params.len()).map(|i| format!("a.get({}).cloned().unwrap_or(Value::Nil)", i)).collect();
            return Some(format!("rt::func(|a: Vec<Value>| {}__new({}))", n, args.join(", ")));
        }
        if self.info.generics.contains_key(n) { return Some(format!("rt::func(|a: Vec<Value>| rt::call_generic({}, a))", lit(n))); }
        None
    }

    fn variant_call(&mut self, name: &str, args: &[Arg]) -> String {
        if name == "Ok" || name == "Err" {
            let a = args.first().map(|a| self.expr(&a.value)).unwrap_or("Value::Nil".into());
            return format!("rt::{}({})", name.to_lowercase(), a);
        }
        let en = self.info.variant_of[name].clone();
        let fields = self.d.enums.iter().find(|e| e.name == en).unwrap().variants.iter().find(|v| v.name == name).unwrap().fields.clone();
        let vals = self.ordered(&fields, args);
        format!("{}__{}({})", en, name, vals.join(", "))
    }

    fn call(&mut self, callee: &Expr, args: &[Arg]) -> String {
        match &callee.kind {
            ExprKind::Ident(n) if !self.is_local(n) && !self.field(n) => {
                if n == "callNext" {
                    return if args.is_empty() { "__next(__args.clone())".into() } else { format!("__next({})", self.args_vec(args)) };
                }
                if self.method(n) { return format!("rt::call_self(&this, {}, {})", lit(n), self.args_vec(args)); }
                if let Some(f) = self.d.funs.get(n).copied() { let v = self.ordered(&f.params, args); return format!("{}({})", fname(n), v.join(", ")); }
                if let Some(c) = self.d.classes.get(n).copied() { let v = self.ordered(&c.params, args); return format!("{}__new({})", n, v.join(", ")); }
                if self.info.variant_of.contains_key(n) { return self.variant_call(n, args); }
                if self.info.generics.contains_key(n) { return format!("rt::call_generic({}, {})", lit(n), self.args_vec(args)); }
                if is_builtin(n) {
                    let a: Vec<String> = args.iter().map(|a| self.expr(&a.value)).collect();
                    let at = |i: usize| a.get(i).cloned().unwrap_or("Value::Nil".into());
                    return match n.as_str() {
                        "println" => format!("rt::println(&{})", if a.is_empty() { "rt::s(\"\")".into() } else { at(0) }),
                        "print" => format!("rt::print(&{})", at(0)),
                        "str" => format!("rt::s(&rt::to_str(&{}))", at(0)),
                        "atom" => format!("rt::atom({})", at(0)),
                        "range" => format!("rt::range(&{}, &{})", at(0), at(1)),
                        "panic" => format!("rt::fail(rt::to_str(&{}))", at(0)),
                        "assert" => format!("rt::assert(&{}, &{})", at(0), if a.len() > 1 { at(1) } else { "rt::s(\"\")".into() }),
                        _ => format!("rt::sheets({}, vec![{}])", lit(n), a.join(", ")),
                    };
                }
                debug_assert!(!is_sheets_lazy(n));
                format!("rt::apply({}, {})", self.rf(callee), self.args_vec(args))
            }
            ExprKind::Member { obj, name, safe } => {
                if let ExprKind::Ident(en) = &obj.kind {
                    if !self.is_local(en) && self.info.enums.contains_key(en) && self.info.variant_of.get(name) == Some(en) {
                        return self.variant_call(name, args);
                    }
                }
                if name == "copy" && args.iter().all(|a| a.name.is_some()) && !args.is_empty() {
                    let o = self.rf(obj);
                    let ch: Vec<String> = args.iter().map(|a| format!("({}, {})", lit(a.name.as_ref().unwrap()), self.expr(&a.value))).collect();
                    return format!("rt::copy({}, vec![{}])", o, ch.join(", "));
                }
                let o = self.rf(obj);
                let av = self.args_vec(args);
                if matches!(obj.kind, ExprKind::This) { return format!("rt::call_self({}, {}, {})", o, lit(name), av); }
                format!("rt::{}({}, {}, {})", if *safe { "call_safe" } else { "call" }, o, lit(name), av)
            }
            _ => { let f = self.rf(callee); format!("rt::apply({}, {})", f, self.args_vec(args)) }
        }
    }

    fn pattern(&mut self, p: &Pattern, acc: &str, conds: &mut Vec<String>, binds: &mut Vec<(String, String)>) {
        match p {
            Pattern::Wild => {}
            Pattern::Bind(n) => binds.push((n.clone(), acc.to_string())),
            Pattern::Lit(e) => conds.push(format!("rt::eq(&{}, &{})", acc, self.expr(e))),
            Pattern::Variant { name, args, .. } => {
                conds.push(format!("rt::is_variant(&{}, {})", acc, lit(name)));
                for (i, a) in args.iter().enumerate() { self.pattern(a, &format!("rt::vfield(&{}, {})", acc, i), conds, binds); }
            }
        }
    }

    pub fn expr(&mut self, e: &Expr) -> String {
        use ExprKind as K;
        match &e.kind {
            K::Int(i) => format!("Value::Int({})", i),
            K::Float(f) => format!("Value::Float({:?})", f),
            K::Decimal(t) => format!("rt::dec({})", lit(t)),
            K::Quantity(x, u) => format!("rt::qty({}, {})", self.expr(x), lit(u)),
            K::Str(segs) => {
                if let [StrSeg::Lit(l)] = segs.as_slice() { return format!("rt::s({})", lit(l)); }
                let parts: Vec<String> = segs.iter().map(|s| match s { StrSeg::Lit(l) => format!("rt::s({})", lit(l)), StrSeg::Expr(x) => self.expr(x) }).collect();
                format!("rt::concat(vec![{}])", parts.join(", "))
            }
            K::Bool(b) => format!("Value::Bool({})", b),
            K::Nil => "Value::Nil".into(),
            K::This => "this.clone()".into(),
            K::Result => "result.clone()".into(),
            K::Old(_, slot) => format!("__old{}.clone()", slot),
            K::Ident(n) => {
                if self.is_local(n) { return format!("{}.clone()", rid(n)); }
                if self.field(n) || self.method(n) { return format!("rt::get(&this, {})", lit(n)); }
                if let Some(v) = self.fn_value(n) { return v; }
                if self.info.variant_of.contains_key(n) {
                    if self.info.variant_fields(n).map_or(false, |f| f.is_empty()) { return format!("{}__{}()", self.info.variant_of[n], n); }
                    let k = self.info.variant_fields(n).map_or(0, |f| f.len());
                    let args: Vec<String> = (0..k).map(|i| format!("a.get({}).cloned().unwrap_or(Value::Nil)", i)).collect();
                    if n == "Ok" || n == "Err" { return format!("rt::func(|a: Vec<Value>| rt::{}({}))", n.to_lowercase(), args.join(", ")); }
                    return format!("rt::func(|a: Vec<Value>| {}__{}({}))", self.info.variant_of[n], n, args.join(", "));
                }
                if is_builtin(n) { return format!("rt::func(|a: Vec<Value>| rt::sheets({}, a))", lit(n)); }
                format!("{}.clone()", rid(n))
            }
            K::CellRef(c) => format!("rt::cell(__sheet, {})", lit(c)),
            K::CellRange(a, b) => format!("rt::cell_range(__sheet, {}, {})", lit(a), lit(b)),
            K::Binary(op, l, r) => {
                match op.as_str() {
                    "&&" => format!("Value::Bool(rt::truthy({}) && rt::truthy({}))", self.rf(l), self.rf(r)),
                    "||" => format!("Value::Bool(rt::truthy({}) || rt::truthy({}))", self.rf(l), self.rf(r)),
                    "?:" => format!("{{ let __t = {}; if __t.is_nil() {{ {} }} else {{ __t }} }}", self.expr(l), self.expr(r)),
                    _ => {
                        let f = match op.as_str() {
                            "+" => "add", "-" => "sub", "*" => "mul", "/" => "div", "%" => "rem", "^" => "pow", "&" => "amp",
                            "==" => "op_eq", "!=" => "op_ne", "<" => "lt", "<=" => "le", ">" => "gt", ">=" => "ge", _ => unreachable!(),
                        };
                        let (a, b) = (self.rf(l), self.rf(r));
                        format!("rt::{}({}, {})", f, a, b)
                    }
                }
            }
            K::Unary(op, x) => format!("rt::{}({})", if op == "-" { "neg" } else { "not" }, self.rf(x)),
            K::Percent(_) | K::Thread { .. } => unreachable!("desugared"),
            K::Call(c, args) => self.call(c, args),
            K::Member { obj, name, safe } => {
                if let ExprKind::Ident(en) = &obj.kind {
                    if !self.is_local(en) && self.info.enums.contains_key(en) && self.info.variant_of.get(name) == Some(en) {
                        return self.variant_call(name, &[]);
                    }
                }
                let o = self.rf(obj);
                format!("rt::{}({}, {})", if *safe { "get_safe" } else { "get" }, o, lit(name))
            }
            K::Super { qualifier, name, args } => {
                let av = self.args_vec(args);
                match qualifier {
                    Some(q) => format!("rt::call_from(&this, {}, {}, {})", lit(q), lit(name), av),
                    None => format!("rt::call_super(&this, {}, {}, {})", lit(self.class.as_deref().unwrap_or("")), lit(name), av),
                }
            }
            K::Index(o, i) => format!("rt::index({}, {})", self.rf(o), self.rf(i)),
            K::Lambda(ps, b) => self.lambda(ps, b),
            K::If(c, t, el) => {
                let cond = self.rf(c);
                let tb = self.block(t);
                let eb = el.as_ref().map(|b| self.block(b)).unwrap_or("{ Value::Nil }".into());
                format!("if rt::truthy({}) {} else {}", cond, tb, eb)
            }
            K::Match(subject, arms) => {
                let lbl = self.fresh("'m");
                let mv = self.fresh("__m");
                let mut out = format!("{}: {{ let {} = {}; ", lbl, mv, self.expr(subject));
                for a in arms {
                    let (mut conds, mut binds) = (vec![], vec![]);
                    self.pattern(&a.pat, &mv, &mut conds, &mut binds);
                    self.scopes.push(binds.iter().map(|b| b.0.clone()).collect());
                    let bs: String = binds.iter().map(|(n, acc)| format!("let mut {}: Value = {}; ", rid(n), acc)).collect();
                    let body = self.expr(&a.body);
                    let inner = match &a.guard {
                        Some(g) => format!("{}if rt::truthy({}) {{ break {} {}; }}", bs, self.rf(g), lbl, body),
                        None => format!("{}break {} {};", bs, lbl, body),
                    };
                    self.scopes.pop();
                    if conds.is_empty() { out.push_str(&format!("{{ {} }} ", inner)); }
                    else { out.push_str(&format!("if {} {{ {} }} ", conds.join(" && "), inner)); }
                }
                out.push_str(&format!("rt::fail(format!(\"no match arm for {{}}\", rt::repr(&{}))) }}", mv));
                out
            }
            K::Vec(items) => { let v: Vec<String> = items.iter().map(|i| self.expr(i)).collect(); format!("rt::vec(vec![{}])", v.join(", ")) }
            K::Map(entries) => {
                if entries.iter().all(|e| matches!(e, MapEntry::Kv(..))) {
                    let v: Vec<String> = entries.iter().map(|en| if let MapEntry::Kv(k, v) = en { format!("({}, {})", self.expr(k), self.expr(v)) } else { unreachable!() }).collect();
                    return format!("rt::map(vec![{}])", v.join(", "));
                }
                let mut s = "{ let mut __mp = rt::map(vec![]); ".to_string();
                for en in entries {
                    match en {
                        MapEntry::Spread(x) => { let v = self.rf(x); s.push_str(&format!("__mp = rt::merge(&__mp, {}); ", v)) }
                        MapEntry::Kv(k, v) => s.push_str(&format!("__mp = rt::assoc(&__mp, {}, {}); ", self.expr(k), self.expr(v))),
                    }
                }
                s.push_str("__mp }");
                s
            }
            K::Try(x) => format!("match rt::try_branch({}) {{ Ok(__v) => __v, Err(__e) => return __e }}", self.expr(x)),
            K::NotNull(x) => format!("rt::not_null({}, \"value\")", self.expr(x)),
            K::Range(a, b) => format!("rt::range({}, {})", self.rf(a), self.rf(b)),
            K::Block(b) => self.block(b),
            K::Is(x, t) => {
                let name = match t { TypeNode::Name { name, .. } => name.clone(), TypeNode::Nullable(_) => "Any".into(), _ => "Any".into() };
                format!("Value::Bool(rt::is_instance({}, {}))", self.rf(x), lit(&name))
            }
            K::Sheet(cells) => {
                let mut parts = vec![];
                for c in cells {
                    if is_formula(&c.value) {
                        let caps = self.capture(&[&c.value], &[]);
                        let saved = std::mem::take(&mut self.loops);
                        self.scopes.push(HashSet::new());
                        let body = self.expr(&c.value);
                        self.scopes.pop();
                        self.loops = saved;
                        parts.push(format!("({}, {{ {}rt::formula(move |__sheet: &Value| -> Value {{ {} }}) }})", lit(&c.cell), caps, body));
                    } else {
                        parts.push(format!("({}, rt::Cell::Val({}))", lit(&c.cell), self.expr(&c.value)));
                    }
                }
                format!("rt::sheet(vec![{}])", parts.join(", "))
            }
        }
    }
}
