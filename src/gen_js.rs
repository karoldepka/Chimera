//! JavaScript backend. Chimera is expression-oriented (if/match/blocks yield values), so
//! expressions are lowered into JS statements plus temporaries, preserving evaluation order.

use std::collections::{HashMap, HashSet};

use crate::ast::*;
use crate::common::{contract_msg, is_formula, order_args, Decls};
use crate::sema::{is_builtin, Info};

const JS_RESERVED: &[&str] = &[
    "arguments", "await", "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do",
    "else", "enum", "eval", "export", "extends", "false", "finally", "for", "function", "if", "implements", "import", "in",
    "instanceof", "interface", "let", "new", "null", "package", "private", "protected", "public", "return", "static",
    "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield", "undefined", "NaN", "Infinity",
];

fn jsname(n: &str) -> String { if JS_RESERVED.contains(&n) { format!("{}$", n) } else { n.to_string() } }
fn fname(n: &str) -> String { if n == "main" { "chimera_main".into() } else { format!("f_{}", n) } }
pub fn lit(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""), '\\' => o.push_str("\\\\"), '\n' => o.push_str("\\n"), '\r' => o.push_str("\\r"), '\t' => o.push_str("\\t"),
            '\u{2028}' => o.push_str("\\u2028"), '\u{2029}' => o.push_str("\\u2029"),
            c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

pub fn generate(p: &Program, info: &Info) -> String {
    let d = Decls::new(p);
    let mut g = J { info, d: &d, buf: vec![], scopes: vec![], class: None, n: 0 };
    let mut out = String::from("// ---- generated by the Chimera compiler. Do not edit.\n");
    for e in &d.enums {
        for v in &e.variants {
            let ps: Vec<String> = v.fields.iter().map(|f| jsname(&f.name)).collect();
            let names: Vec<String> = v.fields.iter().map(|f| lit(&f.name)).collect();
            out.push_str(&format!("function {}__{}({}) {{ return $rt.variant({}, {}, [{}], [{}]); }}\n",
                e.name, v.name, ps.join(", "), lit(&e.name), lit(&v.name), names.join(", "), ps.join(", ")));
        }
    }
    for decl in &p.decls {
        if let Decl::Fun(f) = decl { out.push_str(&g.function(f, &fname(&f.name), false, f.name.clone())); }
    }
    let mut reg = String::new();
    for cname in &info.class_order {
        let c = d.classes[cname];
        out.push_str(&g.class(c, &mut reg));
    }
    for (i, m) in d.methods.iter().enumerate() {
        g.scopes = vec![HashMap::new()];
        g.buf.clear();
        let mut head = String::new();
        for (k, p) in m.params.iter().enumerate() {
            let jn = g.declare(&p.name);
            head.push_str(&format!("  let {} = $args.length > {} ? $args[{}] : null;\n", jn, k, k));
        }
        let v = g.expr(&m.body);
        let body = std::mem::take(&mut g.buf);
        out.push_str(&format!("function {}__m{}($args, $next) {{\n{}{}  return {};\n}}\n", m.name, i, head, indent(&body, 1), v));
        let specs: Vec<String> = m.params.iter().map(|p| match &p.ty { Some(TypeNode::Name { name, .. }) => lit(name), _ => lit("Any") }).collect();
        let q = match m.qualifier.as_str() { "before" => 1, "after" => 2, "around" => 3, _ => 0 };
        reg.push_str(&format!("  $rt.registerMethod({}, {{ qual: {}, specs: [{}], f: {}__m{} }});\n", lit(&m.name), q, specs.join(", "), m.name, i));
    }
    out.push_str(&format!("function $register() {{\n{}}}\n$rt.run(() => {{ $register(); chimera_main(); }});\n", reg));
    out
}

fn indent(lines: &[String], lvl: usize) -> String {
    let pad = "  ".repeat(lvl);
    lines.iter().map(|l| l.lines().map(|x| format!("{}{}\n", pad, x)).collect::<String>()).collect()
}

struct J<'a> {
    info: &'a Info,
    d: &'a Decls<'a>,
    buf: Vec<String>,
    scopes: Vec<HashMap<String, String>>,
    class: Option<String>,
    n: usize,
}

impl<'a> J<'a> {
    fn tmp(&mut self) -> String { self.n += 1; format!("$t{}", self.n) }
    fn emit(&mut self, s: String) { self.buf.push(s); }
    fn lookup(&self, n: &str) -> Option<&String> { self.scopes.iter().rev().find_map(|s| s.get(n)) }
    fn is_local(&self, n: &str) -> bool { self.lookup(n).is_some() }
    fn declare(&mut self, n: &str) -> String {
        let js = if self.is_local(n) { self.n += 1; format!("{}${}", n, self.n) } else { jsname(n) };
        self.scopes.last_mut().unwrap().insert(n.to_string(), js.clone());
        js
    }
    fn field(&self, n: &str) -> bool { self.class.as_ref().and_then(|c| self.info.classes.get(c)).map_or(false, |ci| ci.fields.iter().any(|f| f.name == n)) }
    fn method(&self, n: &str) -> bool { self.class.as_ref().and_then(|c| self.info.classes.get(c)).map_or(false, |ci| ci.methods.contains_key(n)) }
    fn with_buf<T>(&mut self, f: impl FnOnce(&mut Self) -> T) -> (Vec<String>, T) {
        let saved = std::mem::take(&mut self.buf);
        let r = f(self);
        let inner = std::mem::replace(&mut self.buf, saved);
        (inner, r)
    }

    // ------------------------------------------------------------ declarations
    fn function(&mut self, f: &FunDecl, name: &str, method: bool, where_: String) -> String {
        self.scopes = vec![HashMap::new()];
        self.buf.clear();
        let mut ps = vec![];
        if method { ps.push("$this".to_string()); }
        for p in &f.params { ps.push(self.declare(&p.name)); }
        for r in &f.requires {
            let c = self.expr(&r.expr);
            self.emit(format!("if (!$rt.truthy({})) $rt.fail({});", c, lit(&contract_msg("precondition", &where_, r))));
        }
        let body_src = match &f.body { Some(b) => b.clone(), None => Expr::new(ExprKind::Nil, f.span) };
        if f.ensures.is_empty() {
            let v = self.expr(&body_src);
            self.emit(format!("return {};", v));
        } else {
            for (i, o) in f.olds.iter().enumerate() { let v = self.expr(o); self.emit(format!("const $old{} = {};", i, v)); }
            let (inner, v) = self.with_buf(|g| g.expr(&body_src));
            self.emit(format!("const result = (() => {{\n{}  return {};\n}})();", indent(&inner, 1), v));
            self.scopes.last_mut().unwrap().insert("result".into(), "result".into());
            for e in &f.ensures {
                let c = self.expr(&e.expr);
                self.emit(format!("if (!$rt.truthy({})) $rt.fail({});", c, lit(&contract_msg("postcondition", &where_, e))));
            }
            self.emit("return result;".into());
        }
        let body = std::mem::take(&mut self.buf);
        format!("function {}({}) {{\n{}}}\n", name, ps.join(", "), indent(&body, 1))
    }

    fn class(&mut self, c: &ClassDecl, reg: &mut String) -> String {
        let ci = &self.info.classes[&c.name];
        self.class = Some(c.name.clone());
        let mut out = format!("// ---- {} {} (MRO: {})\n", if c.is_trait { "trait" } else { "class" }, c.name, ci.mro.join(" -> "));
        let mut table = vec![];
        for m in &c.methods {
            if m.body.is_none() { continue; }
            let fnn = format!("{}__{}", c.name, m.name);
            out.push_str(&self.function(m, &fnn, true, format!("{}.{}", c.name, m.name)));
            let args: Vec<String> = m.params.iter().enumerate().map(|(i, p)| {
                let def = p.default.as_ref().map(|d| { self.scopes = vec![HashMap::new()]; self.pure(d) }).unwrap_or("null".into());
                format!("a.length > {} ? a[{}] : {}", i, i, def)
            }).collect();
            table.push(format!("[{}, (t, a) => {}(t{}{})]", lit(&m.name), fnn, if args.is_empty() { "" } else { ", " }, args.join(", ")));
        }
        let inv = if c.invariants.is_empty() { "null".to_string() } else {
            self.scopes = vec![HashMap::new()];
            self.buf.clear();
            for i in &c.invariants {
                let v = self.expr(&i.expr);
                let msg = i.tag.as_ref().map(|t| format!("{}: {}", t, i.text)).unwrap_or(i.text.clone());
                self.emit(format!("if (!$rt.truthy({})) return {};", v, lit(&msg)));
            }
            let body = std::mem::take(&mut self.buf);
            out.push_str(&format!("function {}__inv($this) {{\n{}  return null;\n}}\n", c.name, indent(&body, 1)));
            format!("{}__inv", c.name)
        };
        if !c.is_trait {
            self.scopes = vec![HashMap::new()];
            self.buf.clear();
            let ps: Vec<String> = c.params.iter().map(|p| self.declare(&p.name)).collect();
            self.emit(format!("if (!$rt.beginInit($this, {})) return;", lit(&c.name)));
            for s in &c.supers {
                let Some(pc) = self.d.classes.get(&s.name).copied() else { continue };
                if pc.is_trait { continue; }
                let args = s.args.clone().unwrap_or_default();
                let vals = self.ordered(&pc.params, &args);
                self.emit(format!("{}__init($this{}{});", s.name, if vals.is_empty() { "" } else { ", " }, vals.join(", ")));
            }
            for p in &c.params { if p.field.is_some() { let js = self.lookup(&p.name).unwrap().clone(); self.emit(format!("$rt.set($this, {}, {});", lit(&p.name), js)); } }
            for f in &c.fields { let v = self.expr(&f.init); self.emit(format!("$rt.set($this, {}, {});", lit(&f.name), v)); }
            let body = std::mem::take(&mut self.buf);
            out.push_str(&format!("function {}__init($this{}{}) {{\n{}}}\n", c.name, if ps.is_empty() { "" } else { ", " }, ps.join(", "), indent(&body, 1)));
            out.push_str(&format!("function {}__new({}) {{\n  const $this = $rt.newObj({});\n  {}__init($this{}{});\n  return $rt.finishNew($this);\n}}\n",
                c.name, ps.join(", "), lit(&c.name), c.name, if ps.is_empty() { "" } else { ", " }, ps.join(", ")));
        }
        let mro: Vec<String> = ci.mro.iter().map(|m| lit(m)).collect();
        let fields: Vec<String> = ci.fields.iter().map(|f| lit(&f.name)).collect();
        reg.push_str(&format!("  $rt.registerClass({{ name: {}, mro: [{}], methods: [{}], invariant: {}, hasInvariants: {}, data: {}, fields: [{}] }});\n",
            lit(&c.name), mro.join(", "), table.join(", "), inv, ci.has_invariants, ci.is_data, fields.join(", ")));
        self.class = None;
        out
    }

    /// generate an expression that must not need statements (used for default values)
    fn pure(&mut self, e: &Expr) -> String {
        let (pre, v) = self.with_buf(|g| g.expr(e));
        if pre.is_empty() { v } else { format!("(() => {{\n{}  return {};\n}})()", indent(&pre, 1), v) }
    }

    // ------------------------------------------------------------ statements
    /// Emit the block's statements into the current buffer inside `{ }`; the value goes to `target`.
    fn block_into(&mut self, b: &Block, target: Option<&str>) -> Vec<String> {
        self.scopes.push(HashMap::new());
        let (stmts, _) = self.with_buf(|g| {
            let n = b.stmts.len();
            for (i, s) in b.stmts.iter().enumerate() {
                match (s, target) {
                    (Stmt::Expr(e), Some(t)) if i + 1 == n => { let v = g.expr(e); g.emit(format!("{} = {};", t, v)); }
                    _ => g.stmt(s),
                }
            }
            if target.is_some() && !matches!(b.stmts.last(), Some(Stmt::Expr(_))) { g.emit(format!("{} = null;", target.unwrap())); }
        });
        self.scopes.pop();
        stmts
    }

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let { name, init, .. } => {
                let v = self.expr(init);
                let js = self.declare(name);
                self.emit(format!("let {} = {};", js, v));
            }
            Stmt::Assign { target, value, .. } => {
                match &target.kind {
                    ExprKind::Ident(n) if self.is_local(n) => { let v = self.expr(value); let js = self.lookup(n).unwrap().clone(); self.emit(format!("{} = {};", js, v)); }
                    ExprKind::Ident(n) => { let v = self.expr(value); self.emit(format!("$rt.set($this, {}, {});", lit(n), v)); }
                    ExprKind::Member { obj, name, .. } => match &obj.kind {
                        ExprKind::Ident(b) if self.is_local(b) => { let v = self.expr(value); let js = self.lookup(b).unwrap().clone(); self.emit(format!("{} = $rt.setIn({}, {}, {});", js, js, lit(name), v)); }
                        _ => { let r = self.seq(&[obj, value]); self.emit(format!("$rt.set({}, {}, {});", r[0], lit(name), r[1])); }
                    },
                    ExprKind::Index(obj, idx) => match &obj.kind {
                        ExprKind::Ident(b) if self.is_local(b) => { let r = self.seq(&[idx, value]); let js = self.lookup(b).unwrap().clone(); self.emit(format!("{} = $rt.assoc({}, {}, {});", js, js, r[0], r[1])); }
                        ExprKind::Ident(b) if self.field(b) => { let r = self.seq(&[idx, value]); self.emit(format!("$rt.set($this, {f}, $rt.assoc($rt.get($this, {f}), {}, {}));", r[0], r[1], f = lit(b))); }
                        _ => { let r = self.seq(&[obj, idx]); self.emit(format!("$rt.index({}, {});", r[0], r[1])); }
                    },
                    _ => unreachable!(),
                }
            }
            Stmt::Expr(e) => { let v = self.expr(e); if !is_simple(&v) { self.emit(format!("{};", v)); } }
            Stmt::Return(v, _) => { let x = v.as_ref().map(|e| self.expr(e)).unwrap_or("null".into()); self.emit(format!("return {};", x)); }
            Stmt::Break(_) => self.emit("break;".into()),
            Stmt::Continue(_) => self.emit("continue;".into()),
            Stmt::While(c, b) => {
                let (pre, cond) = self.with_buf(|g| g.expr(c));
                let body = self.block_into(b, None);
                if pre.is_empty() {
                    self.emit(format!("while ($rt.truthy({})) {{\n{}}}", cond, indent(&body, 1)));
                } else {
                    self.emit(format!("while (true) {{\n{}  if (!$rt.truthy({})) break;\n{}}}", indent(&pre, 1), cond, indent(&body, 1)));
                }
            }
            Stmt::For(name, it, b) => {
                if let ExprKind::Range(from, to) = &it.kind {
                    let r = self.seq(&[from, to]);
                    let (iv, ev) = (self.tmp(), self.tmp());
                    self.scopes.push(HashMap::new());
                    let js = self.declare(name);
                    let body = self.block_into(b, None);
                    self.scopes.pop();
                    self.emit(format!("for (let {iv} = $rt.asInt({}), {ev} = $rt.asInt({}); {iv} < {ev}; {iv}++) {{\n  const {js} = {iv};\n{}}}", r[0], r[1], indent(&body, 1)));
                    return;
                }
                let src = self.expr(it);
                self.scopes.push(HashMap::new());
                let js = self.declare(name);
                let body = self.block_into(b, None);
                self.scopes.pop();
                self.emit(format!("for (const {} of $rt.iter({})) {{\n{}}}", js, src, indent(&body, 1)));
            }
        }
    }

    // ------------------------------------------------------------ expressions
    /// Evaluate expressions left to right; if a later one needs statements, earlier results are spilled to temps.
    fn seq(&mut self, es: &[&Expr]) -> Vec<String> {
        let mut res: Vec<String> = vec![];
        for e in es {
            let (pre, v) = self.with_buf(|g| g.expr(e));
            if !pre.is_empty() {
                for r in res.iter_mut() {
                    if !is_simple(r) { let t = self.tmp(); self.emit(format!("const {} = {};", t, r)); *r = t; }
                }
                self.buf.extend(pre);
            }
            res.push(v);
        }
        res
    }
    fn args_list(&mut self, args: &[Arg]) -> String {
        let es: Vec<&Expr> = args.iter().map(|a| &a.value).collect();
        format!("[{}]", self.seq(&es).join(", "))
    }
    fn ordered(&mut self, params: &[Param], args: &[Arg]) -> Vec<String> {
        let ord = order_args(params, args);
        let mut es: Vec<Expr> = vec![];
        for (i, p) in params.iter().enumerate() {
            es.push(match ord.get(i).copied().flatten() {
                Some(e) => e.clone(),
                None => p.default.clone().unwrap_or(Expr::new(ExprKind::Nil, p.span)),
            });
        }
        let refs: Vec<&Expr> = es.iter().collect();
        self.seq(&refs)
    }

    fn lambda(&mut self, params: &[Param], body: &Expr, head: &str) -> String {
        self.scopes.push(HashMap::new());
        let ps: Vec<String> = params.iter().map(|p| self.declare(&p.name)).collect();
        let (pre, v) = self.with_buf(|g| g.expr(body));
        self.scopes.pop();
        let ps = if head.is_empty() { format!("({})", ps.join(", ")) } else { head.to_string() };
        if pre.is_empty() { return format!("({} => ({}))", ps, v); }
        format!("({} => {{\n{}  return {};\n}})", ps, indent(&pre, 1), v)
    }

    fn fn_value(&self, n: &str) -> Option<String> {
        if self.d.funs.contains_key(n) { return Some(fname(n)); }
        if self.d.classes.contains_key(n) { return Some(format!("{}__new", n)); }
        if self.info.generics.contains_key(n) { return Some(format!("((...a) => $rt.callGeneric({}, a))", lit(n))); }
        None
    }

    fn variant_call(&mut self, name: &str, args: &[Arg]) -> String {
        if name == "Ok" || name == "Err" {
            let a = self.args_list(args);
            return format!("$rt.{}(...{})", name.to_lowercase(), a);
        }
        let en = self.info.variant_of[name].clone();
        let fields = self.d.enums.iter().find(|e| e.name == en).unwrap().variants.iter().find(|v| v.name == name).unwrap().fields.clone();
        let vals = self.ordered(&fields, args);
        format!("{}__{}({})", en, name, vals.join(", "))
    }

    fn call(&mut self, callee: &Expr, args: &[Arg]) -> String {
        match &callee.kind {
            ExprKind::Ident(n) if !self.is_local(n) && !self.field(n) => {
                if n == "embedFile" {
                    if let [Arg { value: Expr { kind: ExprKind::Str(segs), .. }, .. }] = args {
                        if let [StrSeg::Lit(path)] = segs.as_slice() { return lit(&crate::embed_file(path)); }
                    }
                }
                if n == "callNext" { return if args.is_empty() { "$next($args)".into() } else { format!("$next({})", self.args_list(args)) }; }
                if self.method(n) { let a = self.args_list(args); return format!("$rt.callSelf($this, {}, {})", lit(n), a); }
                if let Some(f) = self.d.funs.get(n).copied() { let v = self.ordered(&f.params, args); return format!("{}({})", fname(n), v.join(", ")); }
                if let Some(c) = self.d.classes.get(n).copied() { let v = self.ordered(&c.params, args); return format!("{}__new({})", n, v.join(", ")); }
                if self.info.variant_of.contains_key(n) { return self.variant_call(n, args); }
                if self.info.generics.contains_key(n) { let a = self.args_list(args); return format!("$rt.callGeneric({}, {})", lit(n), a); }
                if is_builtin(n) {
                    let es: Vec<&Expr> = args.iter().map(|a| &a.value).collect();
                    let a = self.seq(&es);
                    let at = |i: usize| a.get(i).cloned().unwrap_or("null".into());
                    return match n.as_str() {
                        "println" => format!("$rt.println({})", if a.is_empty() { "\"\"".into() } else { at(0) }),
                        "print" => format!("$rt.print({})", at(0)),
                        "str" => format!("$rt.toStr({})", at(0)),
                        "atom" => format!("$rt.atom({})", at(0)),
                        "range" => format!("$rt.range({}, {})", at(0), at(1)),
                        "panic" => format!("$rt.fail($rt.toStr({}))", at(0)),
                        "assert" => format!("$rt.assert({}, {})", at(0), if a.len() > 1 { at(1) } else { "\"\"".into() }),
                        _ => format!("$rt.sheets({}, [{}])", lit(n), a.join(", ")),
                    };
                }
                let f = self.expr(callee);
                let a = self.args_list(args);
                format!("$rt.apply({}, {})", f, a)
            }
            ExprKind::Member { obj, name, safe } => {
                if let ExprKind::Ident(en) = &obj.kind {
                    if !self.is_local(en) && self.info.enums.contains_key(en) && self.info.variant_of.get(name) == Some(en) { return self.variant_call(name, args); }
                }
                if name == "copy" && !args.is_empty() && args.iter().all(|a| a.name.is_some()) {
                    let mut es: Vec<&Expr> = vec![obj];
                    es.extend(args.iter().map(|a| &a.value));
                    let r = self.seq(&es);
                    let ch: Vec<String> = args.iter().enumerate().map(|(i, a)| format!("[{}, {}]", lit(a.name.as_ref().unwrap()), r[i + 1])).collect();
                    return format!("$rt.copy({}, [{}])", r[0], ch.join(", "));
                }
                let mut es: Vec<&Expr> = vec![obj];
                es.extend(args.iter().map(|a| &a.value));
                let r = self.seq(&es);
                let av = format!("[{}]", r[1..].join(", "));
                if matches!(obj.kind, ExprKind::This) { return format!("$rt.callSelf({}, {}, {})", r[0], lit(name), av); }
                format!("$rt.{}({}, {}, {})", if *safe { "callSafe" } else { "call" }, r[0], lit(name), av)
            }
            _ => {
                let mut es: Vec<&Expr> = vec![callee];
                es.extend(args.iter().map(|a| &a.value));
                let r = self.seq(&es);
                format!("$rt.apply({}, [{}])", r[0], r[1..].join(", "))
            }
        }
    }

    fn pattern(&mut self, p: &Pattern, acc: &str, conds: &mut Vec<String>, binds: &mut Vec<(String, String)>) {
        match p {
            Pattern::Wild => {}
            Pattern::Bind(n) => binds.push((n.clone(), acc.to_string())),
            Pattern::Lit(e) => { let v = self.pure(e); conds.push(format!("$rt.eq({}, {})", acc, v)); }
            Pattern::Variant { name, args, .. } => {
                conds.push(format!("$rt.isVariant({}, {})", acc, lit(name)));
                for (i, a) in args.iter().enumerate() { self.pattern(a, &format!("$rt.vfield({}, {})", acc, i), conds, binds); }
            }
        }
    }

    fn expr(&mut self, e: &Expr) -> String {
        use ExprKind as K;
        match &e.kind {
            K::Int(i) => format!("{}n", i),
            K::Float(f) => { let s = format!("{:?}", f); if s.starts_with('-') { format!("({})", s) } else { s } }
            K::Decimal(t) => format!("$rt.dec({})", lit(t)),
            K::Quantity(x, u) => { let v = self.expr(x); format!("$rt.qty({}, {})", v, lit(u)) }
            K::Str(segs) => {
                if let [StrSeg::Lit(l)] = segs.as_slice() { return lit(l); }
                let es: Vec<Expr> = segs.iter().map(|s| match s { StrSeg::Lit(l) => Expr::new(K::Str(vec![StrSeg::Lit(l.clone())]), e.span), StrSeg::Expr(x) => x.clone() }).collect();
                let refs: Vec<&Expr> = es.iter().collect();
                format!("$rt.concat([{}])", self.seq(&refs).join(", "))
            }
            K::Bool(b) => b.to_string(),
            K::Nil => "null".into(),
            K::This => "$this".into(),
            K::Result => "result".into(),
            K::Old(_, slot) => format!("$old{}", slot),
            K::Ident(n) => {
                if let Some(js) = self.lookup(n) { return js.clone(); }
                if self.field(n) || self.method(n) { return format!("$rt.get($this, {})", lit(n)); }
                if let Some(v) = self.fn_value(n) { return v; }
                if self.info.variant_of.contains_key(n) {
                    if n == "Ok" || n == "Err" { return format!("$rt.{}", n.to_lowercase()); }
                    let en = &self.info.variant_of[n];
                    if self.info.variant_fields(n).map_or(false, |f| f.is_empty()) { return format!("{}__{}()", en, n); }
                    return format!("{}__{}", en, n);
                }
                if is_builtin(n) { return format!("((...a) => $rt.sheets({}, a))", lit(n)); }
                jsname(n)
            }
            K::CellRef(c) => format!("$rt.cell($sheet, {})", lit(c)),
            K::CellRange(a, b) => format!("$rt.cellRange($sheet, {}, {})", lit(a), lit(b)),
            K::Binary(op, l, r) => match op.as_str() {
                "&&" | "||" => {
                    let a = self.expr(l);
                    let (pre, b) = self.with_buf(|g| g.expr(r));
                    if pre.is_empty() { return format!("($rt.truthy({}) {} $rt.truthy({}))", a, op, b); }
                    let t = self.tmp();
                    self.emit(format!("let {} = $rt.truthy({});", t, a));
                    self.emit(format!("if ({}{}) {{\n{}  {} = $rt.truthy({});\n}}", if op == "&&" { "" } else { "!" }, t, indent(&pre, 1), t, b));
                    t
                }
                "?:" => {
                    let a = self.expr(l);
                    let (pre, b) = self.with_buf(|g| g.expr(r));
                    if pre.is_empty() { return format!("({} ?? {})", a, b); }
                    let t = self.tmp();
                    self.emit(format!("let {} = {};", t, a));
                    self.emit(format!("if ({} === null) {{\n{}  {} = {};\n}}", t, indent(&pre, 1), t, b));
                    t
                }
                _ => {
                    let r2 = self.seq(&[l, r]);
                    let f = match op.as_str() {
                        "+" => "add", "-" => "sub", "*" => "mul", "/" => "div", "%" => "rem", "^" => "pow", "&" => "amp",
                        "==" => "opEq", "!=" => "opNe", "<" => "lt", "<=" => "le", ">" => "gt", ">=" => "ge", _ => unreachable!(),
                    };
                    format!("$rt.{}({}, {})", f, r2[0], r2[1])
                }
            },
            K::Unary(op, x) => { let v = self.expr(x); format!("$rt.{}({})", if op == "-" { "neg" } else { "not" }, v) }
            K::Percent(_) | K::Thread { .. } => unreachable!("desugared"),
            K::Call(c, args) => self.call(c, args),
            K::Member { obj, name, safe } => {
                if let ExprKind::Ident(en) = &obj.kind {
                    if !self.is_local(en) && self.info.enums.contains_key(en) && self.info.variant_of.get(name) == Some(en) { return self.variant_call(name, &[]); }
                }
                let o = self.expr(obj);
                format!("$rt.{}({}, {})", if *safe { "getSafe" } else { "get" }, o, lit(name))
            }
            K::Super { qualifier, name, args } => {
                let a = self.args_list(args);
                match qualifier {
                    Some(q) => format!("$rt.callFrom($this, {}, {}, {})", lit(q), lit(name), a),
                    None => format!("$rt.callSuper($this, {}, {}, {})", lit(self.class.as_deref().unwrap_or("")), lit(name), a),
                }
            }
            K::Index(o, i) => { let r = self.seq(&[o, i]); format!("$rt.index({}, {})", r[0], r[1]) }
            K::Lambda(ps, b) => self.lambda(ps, b, ""),
            K::If(c, t, el) => {
                let cond = self.expr(c);
                let tv = self.tmp();
                let tb = self.block_into(t, Some(&tv));
                let eb = match el { Some(b) => self.block_into(b, Some(&tv)), None => vec![format!("{} = null;", tv)] };
                self.emit(format!("let {};", tv));
                self.emit(format!("if ($rt.truthy({})) {{\n{}}} else {{\n{}}}", cond, indent(&tb, 1), indent(&eb, 1)));
                tv
            }
            K::Block(b) => {
                if let [Stmt::Expr(x)] = b.stmts.as_slice() { return self.expr(x); }
                let tv = self.tmp();
                let body = self.block_into(b, Some(&tv));
                self.emit(format!("let {};", tv));
                self.emit(format!("{{\n{}}}", indent(&body, 1)));
                tv
            }
            K::Match(subject, arms) => {
                let sv = self.expr(subject);
                let (tv, lbl, mv) = (self.tmp(), self.tmp().replace('$', "m"), self.tmp());
                let mut lines = vec![format!("const {} = {};", mv, sv)];
                for a in arms {
                    let (mut conds, mut binds) = (vec![], vec![]);
                    self.pattern(&a.pat, &mv, &mut conds, &mut binds);
                    self.scopes.push(HashMap::new());
                    let bl: Vec<String> = binds.iter().map(|(n, acc)| { let js = self.declare(n); format!("const {} = {};", js, acc) }).collect();
                    let (inner, ()) = self.with_buf(|g| {
                        let body_into = |g: &mut Self| {
                            let v = g.expr(&a.body);
                            g.emit(format!("{} = {};", tv, v));
                            g.emit(format!("break {};", lbl));
                        };
                        match &a.guard {
                            Some(gd) => {
                                let gv = g.expr(gd);
                                let (b, ()) = g.with_buf(body_into);
                                g.emit(format!("if ($rt.truthy({})) {{\n{}}}", gv, indent(&b, 1)));
                            }
                            None => body_into(g),
                        }
                    });
                    self.scopes.pop();
                    let mut blk = bl;
                    blk.extend(inner);
                    if conds.is_empty() { lines.push(format!("{{\n{}}}", indent(&blk, 1))); }
                    else { lines.push(format!("if ({}) {{\n{}}}", conds.join(" && "), indent(&blk, 1))); }
                }
                lines.push(format!("$rt.fail(`no match arm for ${{$rt.repr({})}}`);", mv));
                self.emit(format!("let {};", tv));
                self.emit(format!("{}: {{\n{}}}", lbl, indent(&lines, 1)));
                tv
            }
            K::Vec(items) => { let refs: Vec<&Expr> = items.iter().collect(); format!("[{}]", self.seq(&refs).join(", ")) }
            K::Map(entries) => {
                let mut es: Vec<&Expr> = vec![];
                for en in entries { match en { MapEntry::Spread(x) => es.push(x), MapEntry::Kv(k, v) => { es.push(k); es.push(v); } } }
                let r = self.seq(&es);
                let mut i = 0;
                if entries.iter().all(|e| matches!(e, MapEntry::Kv(..))) {
                    let pairs: Vec<String> = entries.iter().map(|_| { let p = format!("[{}, {}]", r[i], r[i + 1]); i += 2; p }).collect();
                    return format!("$rt.map([{}])", pairs.join(", "));
                }
                let mut acc = "$rt.map([])".to_string();
                for en in entries {
                    match en {
                        MapEntry::Spread(_) => { acc = format!("$rt.merge({}, {})", acc, r[i]); i += 1; }
                        MapEntry::Kv(..) => { acc = format!("$rt.assoc({}, {}, {})", acc, r[i], r[i + 1]); i += 2; }
                    }
                }
                acc
            }
            K::Try(x) => {
                let v = self.expr(x);
                let t = self.tmp();
                self.emit(format!("const {} = $rt.tryBranch({});", t, v));
                self.emit(format!("if ({}.err) return {}.v;", t, t));
                format!("{}.v", t)
            }
            K::NotNull(x) => { let v = self.expr(x); format!("$rt.notNull({}, \"value\")", v) }
            K::Range(a, b) => { let r = self.seq(&[a, b]); format!("$rt.range({}, {})", r[0], r[1]) }
            K::Is(x, t) => {
                let name = match t { TypeNode::Name { name, .. } => name.clone(), _ => "Any".into() };
                let v = self.expr(x);
                format!("$rt.isInstance({}, {})", v, lit(&name))
            }
            K::Sheet(cells) => {
                let mut parts = vec![];
                for c in cells {
                    if is_formula(&c.value) {
                        let f = self.lambda(&[], &c.value, "($sheet)");
                        parts.push(format!("[{}, $rt.formula({})]", lit(&c.cell), f));
                    } else {
                        let v = self.expr(&c.value);
                        parts.push(format!("[{}, {}]", lit(&c.cell), v));
                    }
                }
                format!("$rt.sheet([{}])", parts.join(", "))
            }
        }
    }
}

/// Expressions that are safe to evaluate later / drop (no side effects, not reassignable).
fn is_simple(s: &str) -> bool {
    let t = s.trim();
    t == "null" || t == "true" || t == "false"
        || t.starts_with("$t") && t[2..].chars().all(|c| c.is_ascii_digit())
        || t.ends_with('n') && t[..t.len() - 1].trim_start_matches('-').chars().all(|c| c.is_ascii_digit()) && t.len() > 1
        || (t.starts_with('"') && t.ends_with('"') && !t[1..t.len() - 1].contains('"'))
}

